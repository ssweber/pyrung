def _generate_agents_md(
    rungs: list[_AnalyzedRung],
    collection: _OperandCollection,
    subroutines: list[_SubroutineInfo],
    machine_name: str,
) -> str:
    """Generate AGENTS.md with program-specific metadata."""
    shape = _build_program_shape(rungs, collection, subroutines)

    sections: list[str] = []
    sections.append(f"# Machine: {machine_name}\n")

    # --- Cheatsheet + program files ---
    sections.append("""\
Read `click-cheatsheet.md` first. The program is ladder logic as Python — it
mirrors what the engineer sees in the Click GUI editor. Some names differ from
Click: Set → `latch`, Math → `calc`.

Then read the program:
- `tags.py` — tag declarations, types, metadata, TagMap
- `main.py` — main rungs and subroutine calls
- `subroutines/` — individual subroutine files
""")

    # --- Program shape ---
    shape_lines = [
        "## Program shape\n",
        f"- Main: {shape['main_rungs']} rungs, {shape['sub_count']} subroutines",
    ]
    for s in shape["subs"]:
        shape_lines.append(f"- `{s['name']}`: {s['rungs']} rungs — {s['desc']}")
    shape_lines.append(f"- Tags: {shape['tag_summary']}")
    sections.append("\n".join(shape_lines) + "\n")

    # --- Tools ---
    sections.append("""\
## Tools

Run `uv sync` first — it creates the project venv and installs pyrung, which
both tools below need. Without it, `pyrung` and `clicknick-cli` aren't available.

Two CLI tools. Chain commands with `;` to avoid repeated process launches.

- **pyrung live** — simulation and analysis (patch, force, step, why, how)
- **clicknick-cli** — push annotations and rung edits back to Click

## Snapshot prerequisite

For diagnosis to be useful, the simulation must be loaded with a snapshot from
the faulted machine. If `why()` shows everything at defaults, ask the engineer
to load a tag dump (Data > Read Data from PLC > All > Save in Click, then
select in ClickNick before starting DAP).

## Working with the program

Read the code before running tools. `main.py` has the scan order and subroutine
calls. Each `subroutines/*.py` file has the logic for one function — state
machines, interlocks, alarms. Read the subroutines relevant to the problem,
not all 30+.

    pyrung live "step 5"
    pyrung live "get StateCurrent Running FaultAlarm"

`step` runs scans. `get` reads tag values. Chain with `;` to patch-step-observe
in one command.

## Analysis tools — escalation ladder

Each level costs more but answers a harder question. Start at the top, escalate
when the answer isn't enough.

### 1. Understand the program (no snapshot needed)

    pyrung live "dataview i:"
    pyrung live "dataview fill"
    pyrung live "upstream ConveyorMotor"
    pyrung live "simplified ConveyorMotor"

`dataview` discovers what exists (`i:` inputs, `t:` terminals, or search by
name). `upstream`/`downstream` trace dependencies. `simplified` resolves
intermediate tags to a Boolean expression over root inputs.

### 2. Diagnose — why is this tag at this value?

    pyrung live "why FaultAlarm"
    pyrung live "why FaultAlarm MotorStall"

`why()` walks backward from a tag and explains how it reached its current value.
Each rung shows its contacts; `*` marks blocked paths. Multiple tags merge into
one unified explanation. This is your first tool on a service call.

### 3. Test a hypothesis — patch, step, observe

`patch` sets a value once. The program runs normally from there.

    pyrung live "patch StartBtn true; step 1; why Running"

`force` pins the value across scans — simulates a stuck sensor or failed
component:

    pyrung live "force FlowSensor false; step 10; why FaultAlarm"

Each `why()` shows what remains. Iterate until you understand the causal chain.

### 4. Projected queries — what-if without running scans

    pyrung live "cause Running to=false"
    pyrung live "effect StartBtn from=false"
    pyrung live "recovers FaultLatch"

`cause` finds what would need to change to reach a value. `effect` traces what
a change would propagate to. `recovers` checks whether a latched bit has a
clear path. No scans needed — these are structural.

### 5. Steer — how do I reach a target state?

    pyrung live "how StateCurrent == 6"
    pyrung live "how Running"
    pyrung live "how StateCurrent == 6 avoid StateCurrent == 3"

`how()` is an experimental steering aid. It reads the program backward, tries
changes on a fork, and reports a replayable path when it finds one. Use `avoid`
to exclude states from the path.

Treat a failed search narrowly: if `how()` does not find a path, that does not
mean the program is broken or the target is unreachable. It can mean only that
the bounded search ran out of safe, evidence-backed actions for this snapshot.
Continue with `why()`, focused patch/step experiments, and direct ladder review.

## Add & annotate tags (edit tags.py, then `tag apply`)

Two ways to change a tag, same landing spot — both stage unsaved edits in the
Address Editor for the engineer to review and Sync.

**Edit `tags.py`** (default, same as you edit rungs) — add a nickname on an
unused address, or annotate a slot with kwargs, then apply the whole diff:

    ds.slot(568, name='Heat_Limit_Ts', uom='degF')
    ds.slot(30, name='StateCurrent', choices={0:'IDLE', 1:'FILLING', 3:'FAULTED'})

    clicknick-cli tag apply     # diff tags.py -> Address Editor, "Changed" filter

`tag apply` lands only the changed rows and opens the Address Editor on them —
the tag counterpart of the rung Copy/paste step.

**One-off `tag set-*`** — a single change without touching the file:

    clicknick-cli "tag set-choices StateCurrent IDLE:0 FILLING:1 FAULTED:3"

### Save order

A save in Click regenerates pyrung_project/ and discards anything not yet
applied — un-pasted rungs, un-Synced tags. **So never save while edits are still
pending.** When a change touches both tags and rungs, ask the engineer which
order they want:

- **Together** — apply tags + rungs, then one save.
- **Tags first** — apply + Sync + save *before* you write any rung code (nothing
  pending to lose).

## Edit and apply logic changes

New logic usually needs a spare address. `unused` returns the next free
address(es) — not used in the program and carrying no content — so you never
collide with an existing tag:

    clicknick-cli unused C            # next free C bit -> C5
    clicknick-cli unused C1031 C1414  # one free bit near each neighbor (distinct)
    clicknick-cli unused DS 3         # 3 consecutive free DS

Browse existing rungs:

    clicknick-cli rung list
    clicknick-cli rung list init
    clicknick-cli rung preview --select r3

Edit `main.py` or `subroutines/*.py` directly. Then:

1. `clicknick-cli rung apply <file>` — convert to ladder CSVs in csv_output/
2. `clicknick-cli rung preview <file>` — opens preview window with diff
3. Engineer clicks Copy, pastes in Click, saves
4. ScrWatcher detects save → auto-regenerates pyrung_project/

Verify every logic change with focused tests and direct patch/step scenarios,
including the failure case. `how()` can provide additional evidence when it
finds a path, but its failure to find one is not a failed verification.

## Reference

- `tags.py`, `main.py`, `subroutines/` — pyrung model of this machine's logic
- `click-cheatsheet.md` — pyrung DSL quick reference (read first)
- `pyrung live help` — full command list
""")

    return "\n".join(sections)


def _build_program_shape(
    rungs: list[_AnalyzedRung],
    collection: _OperandCollection,
    subroutines: list[_SubroutineInfo],
) -> dict:
    """Extract program shape metadata for AGENTS.md."""
    # Tag type distribution (exclude system tags)
    type_counts: dict[str, int] = {}
    for decl in collection.tags.values():
        if decl.block_var in _SYSTEM_BLOCK_VARS:
            continue
        type_counts[decl.tag_type] = type_counts.get(decl.tag_type, 0) + 1

    tag_parts = [f"{count} {typ}" for typ, count in sorted(type_counts.items())]
    tag_summary = ", ".join(tag_parts) if tag_parts else "none"

    subs = []
    for sub in subroutines:
        subs.append(
            {
                "name": sub.name,
                "rungs": len(sub.analyzed),
                "desc": _describe_subroutine(sub),
            }
        )

    return {
        "main_rungs": len(rungs),
        "sub_count": len(subroutines),
        "subs": subs,
        "tag_summary": tag_summary,
    }


def _describe_subroutine(sub: _SubroutineInfo) -> str:
    """One-line description of a subroutine's purpose."""
    if sub.analyzed and sub.analyzed[0].comment:
        return _first_meaningful_line(sub.analyzed[0].comment)
    return sub.name


def _first_meaningful_line(comment: str) -> str:
    """Extract the first non-decoration line from a comment block."""
    for line in comment.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        # Skip section-heading decoration (===, ---, ###, ***)
        if len(stripped) >= 3 and len(set(stripped) - {" "}) == 1:
            continue
        if stripped.startswith(("#", "=", "-", "*")) and stripped.rstrip("#=-* ") == "":
            continue
        return stripped
    return comment.splitlines()[0].strip()


