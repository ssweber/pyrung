def _generate_tags_file(collection: _OperandCollection) -> str:
    """Generate tags.py: declarations + TagMap."""
    lines: list[str] = [_GENERATED_HEADER, ""]

    # Imports
    _emit_tags_imports(lines, collection)
    lines.append("")

    if collection.physical_decls:
        lines.append("# --- Physical ---")
        _emit_physical_declarations(lines, collection)
        lines.append("")

    # Tag declarations
    if _has_flat_tags(collection):
        lines.append("# --- Tags ---")
        _emit_slot_aliases(lines, collection, suppress_comments=True)
        lines.append("")

    if collection.timer_counter_clones:
        lines.append("# --- Clones ---")
        _emit_tc_clone_declarations(lines, collection)
        lines.append("")

    if collection.plain_blocks:
        lines.append("# --- Blocks ---")
        _emit_plain_block_declarations(lines, collection)
        lines.append("")

    # Structure declarations
    if collection.structures:
        lines.append("# --- Structures ---")
        _emit_structure_declarations(lines, collection)
        lines.append("")

    # Slot name overrides for nicknamed addresses inside ranges
    _emit_slot_overrides(lines, collection)

    # TagMap
    lines.append("# --- Tag Map ---")
    _emit_tag_map(lines, collection)
    lines.append("")

    return "\n".join(lines) + "\n"


def _emit_tags_imports(lines: list[str], collection: _OperandCollection) -> None:
    """Emit imports for tags.py (types, blocks, TagMap)."""
    core: list[str] = []

    # Block/TagType for reconstructed plain named blocks
    if collection.plain_blocks:
        core.append("Block")
        core.append("TagType")

    # Structure decorators
    has_named_array = any(s.structure_type == "named_array" for s in collection.structures)
    has_udt = any(s.structure_type == "udt" for s in collection.structures)
    if collection.physical_decls:
        core.append("Physical")
    if has_named_array:
        core.append("named_array")
    if has_udt:
        core.append("udt")
    if _structure_needs_field_import(collection):
        core.append("Field")
    if _structure_uses_auto(collection):
        core.append("auto")

    # Built-in Timer/Counter UDTs
    if collection.used_instructions & {"on_delay", "off_delay"}:
        core.append("Timer")
    if collection.used_instructions & {"count_up", "count_down"}:
        core.append("Counter")

    # Tag types (needed for structure field types, not for flat tags which are slot aliases)
    if collection.structures or collection.plain_blocks:
        for tt in sorted(collection.used_types):
            if tt not in core:
                core.append(tt)

    if core:
        lines.append(f"from pyrung import {', '.join(core)}")

    # Click imports
    click: list[str] = ["ClickBlocks", "TagMap"]
    lines.append(f"from pyrung.click import {', '.join(click)}")

    if collection.used_blocks:
        # Keep the ClickBlockSet bound as ``blocks`` so project_to_csv.py can pass
        # it to to_nickname_file(blocks=...) — without it, configured-but-unmapped
        # slots (the bulk of nicknames + all annotations) are dropped.
        lines.append("blocks = ClickBlocks()")
        lines.append(
            "x, y, c, t, ct, sc, ds, dd, dh, df, xd, yd, xd0u, yd0u, td, ctd, sd, txt = blocks"
        )

    # Expression functions
    if collection.used_expr_funcs:
        expr = sorted(collection.used_expr_funcs)
        lines.append(f"from pyrung.core.expression import {', '.join(expr)}")


